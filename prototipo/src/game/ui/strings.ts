let current: Lang = "pt";
const listeners = new Set<() => void>();

export function getLanguage(): Lang {
  return current;
}

export function setLanguage(lang: Lang): void {
  if (lang === current) return;
  current = lang;
  if (typeof document !== "undefined") document.documentElement.lang = lang;
  for (const cb of listeners) cb();
}

/** Inscreve para reagir à troca de idioma; retorna função para cancelar. */
export function onLanguageChange(cb: () => void): () => void {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

/** Interpola `{nome}` numa string de T (ex.: F("camaraAria", { n: 3, t: 7 })). */
export function F(key: StringKey, vars: Record<string, string | number>): string {
  return T[key].replace(/\{(\w+)\}/g, (_m, k: string) => String(vars[k] ?? ""));
}

export const T = new Proxy({} as Record<StringKey, string>, {
  get(_t, key) {
    const k = key as StringKey;
    return (current === "en" ? EN : PT)[k] ?? PT[k];
  },
}) as Record<StringKey, string>;
